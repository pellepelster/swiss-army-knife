// the icons of Font Awesome that sak-frontend uses (mise run frontend:icons), so the start bundle
// stays small: src/icons/icons.css with the rules of fontawesome.min.css but only the icons named in
// src/app (fa-<name>), and src/icons/fa-solid-900.woff2, the solid font cut to their glyphs with
// pyftsubset of fonttools (mise.toml). --check writes nothing and fails while the committed css is
// not current (icons.spec.ts)
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontend = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontawesome = join(frontend, 'node_modules', '@fortawesome', 'fontawesome-free');
const target = join(frontend, 'src', 'icons');

// the classes fa-<name> in the code of the app, the specs left out
function usedClasses(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return usedClasses(path);
    if (!/\.(ts|html)$/.test(entry.name) || entry.name.endsWith('.spec.ts')) return [];
    return [...readFileSync(path, 'utf8').matchAll(/\bfa-[a-z0-9-]+/g)].map((match) => match[0]);
  });
}
const used = new Set(usedClasses(join(frontend, 'src', 'app')));

// a rule of an icon: its classes and its code point, e.g. .fa-camera,.fa-camera-alt{--fa:"\f030"}
const ICON = /^((?:\.fa-[a-z0-9-]+,?)+)\{--fa:"\\([0-9a-f]+)"\}$/;

// the minified css as its top-level rules, a block (@keyframes, @supports) as one
function rules(css) {
  const out = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}' && --depth === 0) {
      out.push(css.slice(start, i + 1).trim());
      start = i + 1;
    }
  }
  return out;
}

const codePoints = new Set();
const kept = rules(
  readFileSync(join(fontawesome, 'css', 'fontawesome.min.css'), 'utf8').replace(
    /\/\*[\s\S]*?\*\//g,
    '',
  ),
).flatMap((rule) => {
  const icon = rule.match(ICON);
  if (!icon) return [rule];
  const classes = icon[1].split(',').filter((name) => used.has(name.slice(1)));
  if (classes.length === 0) return [];
  codePoints.add(icon[2]);
  return [`${classes.join(',')}{--fa:"\\${icon[2]}"}`];
});
// the solid style, its font the cut one next to the css
const solid = readFileSync(join(fontawesome, 'css', 'solid.min.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace('url(../webfonts/fa-solid-900.woff2)', 'url(fa-solid-900.woff2)')
  .trim();

const version = JSON.parse(readFileSync(join(fontawesome, 'package.json'), 'utf8')).version;
const css =
  `/* generated by scripts/icons.mjs (mise run frontend:icons), not edited: Font Awesome Free ${version}\n` +
  ' * (https://fontawesome.com, icons CC BY 4.0, fonts SIL OFL 1.1, code MIT) with the icons src/app uses */\n' +
  [...kept, solid].join('\n') +
  '\n';

if (process.argv.includes('--check')) {
  if (readFileSync(join(target, 'icons.css'), 'utf8') !== css) {
    console.error('src/icons/icons.css is not current, run mise run frontend:icons');
    process.exit(1);
  }
} else {
  writeFileSync(join(target, 'icons.css'), css);
  execFileSync('pyftsubset', [
    join(fontawesome, 'webfonts', 'fa-solid-900.woff2'),
    `--unicodes=${[...codePoints]
      .sort()
      .map((point) => `U+${point}`)
      .join(',')}`,
    '--flavor=woff2',
    `--output-file=${join(target, 'fa-solid-900.woff2')}`,
  ]);
}
